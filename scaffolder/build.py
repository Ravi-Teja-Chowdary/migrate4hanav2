"""
scaffolder.build — entry point for generating spine modules from JSON definitions.

Usage
-----
Generate a single object::

    python -m scaffolder.build InventoryReservation

Regenerate all (skips objects with generator='manual')::

    python -m scaffolder.build --all

CI drift detection (fails non-zero if any generated file would differ)::

    python -m scaffolder.build --all --check

Init / sync the DQ rule library into lambda/utils/dq_rules/ (idempotent)::

    python -m scaffolder.build --sync-rules

Determinism
-----------
The generator is fully deterministic. Re-running against the same JSON
produces byte-identical output (no timestamps in headers, only the source
SHA). This is asserted by acceptance criterion §11.7 in SCAFFOLDER_SPEC.md.
"""
from __future__ import annotations

import argparse
import filecmp
import hashlib
import json
import os
import py_compile
import shutil
import sys
import tempfile
from pathlib import Path
from typing import Optional


# Repo-relative anchors. The scaffolder package lives at
# <repo>/scaffolder/, so the repo root is one level up.
SCAFFOLDER_DIR = Path(__file__).resolve().parent
REPO_ROOT      = SCAFFOLDER_DIR.parent
DEFINITIONS    = REPO_ROOT / "definitions"
LAMBDA_UTILS   = REPO_ROOT / "lambda" / "utils"
DQ_RULES_DEST  = LAMBDA_UTILS / "dq_rules"
TEMPLATES_DIR  = SCAFFOLDER_DIR / "templates"
SCHEMA_PATH    = SCAFFOLDER_DIR / "object_definition.schema.json"
RULES_SRC      = SCAFFOLDER_DIR / "rules"


SCAFFOLDER_VERSION = "1.0.0"


# ─────────────────────────────────────────────────────────────────────────────
# Helpers
# ─────────────────────────────────────────────────────────────────────────────
def _snake_case(name: str) -> str:
    """PascalCase → snake_case (e.g., PurchaseRequisition → purchase_requisition)."""
    out = []
    for i, ch in enumerate(name):
        if ch.isupper() and i > 0 and not name[i - 1].isupper():
            out.append("_")
        out.append(ch.lower())
    return "".join(out)


def _sha256(s: str) -> str:
    return hashlib.sha256(s.encode("utf-8")).hexdigest()


def _canonical_json(obj) -> str:
    """JSON with sorted keys, no trailing whitespace — what we hash."""
    return json.dumps(obj, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def _python_repr(v):
    """Stable Python repr() for use inside Jinja templates."""
    return repr(v)


def _repr_dict(v):
    """Render a dict in deterministic key order so codegen is byte-stable."""
    if v is None:
        return "{}"
    if isinstance(v, dict):
        if not v:
            return "{}"
        parts = []
        for k in sorted(v.keys(), key=str):
            parts.append(f"{repr(k)}: {repr(v[k])}")
        return "{" + ", ".join(parts) + "}"
    return repr(v)


def _load_schema():
    with open(SCHEMA_PATH, "r", encoding="utf-8") as f:
        return json.load(f)


def _load_definition(name_or_path: str):
    """Accept either an object_type name (looks up definitions/<name>.json) or
    a full path. Returns (path, parsed_dict, raw_json_text)."""
    p = Path(name_or_path)
    if not p.suffix:
        p = DEFINITIONS / f"{name_or_path}.json"
    if not p.is_absolute():
        # try relative to repo root if user passed a partial path
        if not p.exists():
            p = REPO_ROOT / name_or_path
    if not p.exists():
        raise FileNotFoundError(f"definition not found: {p}")
    raw = p.read_text(encoding="utf-8")
    return p, json.loads(raw), raw


# ─────────────────────────────────────────────────────────────────────────────
# Rule library sync
# ─────────────────────────────────────────────────────────────────────────────
def sync_rules() -> tuple[int, list[str]]:
    """Copy scaffolder/rules/*.py into lambda/utils/dq_rules/ idempotently.

    Returns (files_written, file_list).
    """
    DQ_RULES_DEST.mkdir(parents=True, exist_ok=True)
    written = 0
    files: list[str] = []
    for src in sorted(RULES_SRC.glob("*.py")):
        if src.name == "__init__.py":
            continue
        dst = DQ_RULES_DEST / src.name
        # Write only if content actually differs (preserves mtime on no-op).
        if dst.exists() and src.read_bytes() == dst.read_bytes():
            continue
        shutil.copyfile(src, dst)
        written += 1
        files.append(src.name)

    # __init__.py in the destination: produce a stable import-everything header
    # whose content is fully derived from the rules/ directory listing.
    rule_names = sorted(
        p.stem for p in RULES_SRC.glob("*.py") if p.name != "__init__.py"
    )
    init_lines = [
        '"""Generated by scaffolder/build.py — DO NOT EDIT.',
        'Sourced from scaffolder/rules/.',
        '"""',
        "from __future__ import annotations",
        "",
    ]
    for r in rule_names:
        init_lines.append(f"from .{r} import {r}")
    init_lines.append("")
    init_lines.append("RULES = {")
    for r in rule_names:
        init_lines.append(f"    {r!r}: {r},")
    init_lines.append("}")
    init_lines.append("")
    new_init = "\n".join(init_lines)
    dst_init = DQ_RULES_DEST / "__init__.py"
    if not dst_init.exists() or dst_init.read_text(encoding="utf-8") != new_init:
        dst_init.write_text(new_init, encoding="utf-8")
        written += 1
        files.append("__init__.py")
    return written, files


def known_rules() -> set[str]:
    """Read scaffolder/rules/ and return the set of rule_name strings."""
    return {p.stem for p in RULES_SRC.glob("*.py") if p.name != "__init__.py"}


# ─────────────────────────────────────────────────────────────────────────────
# Schema validation
# ─────────────────────────────────────────────────────────────────────────────
def _validate_schema(definition: dict) -> list[str]:
    try:
        import jsonschema
    except ImportError:
        return ["jsonschema package not installed (pip install jsonschema)"]
    schema = _load_schema()
    validator = jsonschema.Draft202012Validator(schema)
    errors = []
    for err in sorted(validator.iter_errors(definition), key=lambda e: e.path):
        path = "/".join(str(p) for p in err.path) or "<root>"
        errors.append(f"{path}: {err.message}")
    return errors


# ─────────────────────────────────────────────────────────────────────────────
# Template rendering
# ─────────────────────────────────────────────────────────────────────────────
def _build_context(definition: dict, source_sha: str) -> dict:
    """Flatten the JSON definition into a deterministic Jinja context.

    Every container is sorted so iteration order is stable across runs.
    """
    obj          = definition["object_type"]
    snake        = _snake_case(obj)

    extract      = definition.get("extract", {}) or {}
    transform    = definition.get("transform", {}) or {}
    load         = definition.get("load", {}) or {}
    verify       = definition.get("verify", {}) or {}
    extensions   = definition.get("extensions", {}) or {}
    telemetry    = definition.get("telemetry", {}) or {}
    fk           = definition.get("fk", {}) or {}
    version_rt   = definition.get("version_routing", {}) or {}

    field_maps      = transform.get("field_maps", {}) or {}
    item_field_maps = transform.get("item_field_maps", {}) or {}
    value_maps      = transform.get("value_maps", {}) or {}
    constants_header = transform.get("constants_header", {}) or {}
    constants_item   = transform.get("constants_item", {}) or {}
    dq_gates        = transform.get("dq_gates", []) or []

    # Sort containers for determinism
    field_maps_sorted      = sorted(field_maps.items())
    item_field_maps_sorted = sorted(item_field_maps.items())
    value_maps_sorted = [
        (tgt, sorted(vmap.items()))
        for tgt, vmap in sorted(value_maps.items())
    ]
    dq_gates_sorted = [
        {
            "field":     g["field"],
            "rule":      g["rule"],
            "rule_args": g.get("rule_args", {}) or {},
            "on_fail":   g.get("on_fail", "dead_letter"),
            "code":      g["code"],
        }
        for g in sorted(dq_gates, key=lambda x: (x["field"], x["code"]))
    ]
    fk_fields_sorted = sorted(fk.items())

    # Primary + non-primary tables for the MC + LTMOM templates
    tables = extract.get("tables", [])
    primary_tables = [t for t in tables if t.get("primary")]
    primary_table = primary_tables[0] if primary_tables else (tables[0] if tables else {})
    non_primary_tables = [t for t in tables if not t.get("primary")]

    # BAPI bits (with safe defaults so MC-only or IDoc-only objects still build)
    bapi = load.get("bapi", {}) or {}

    # Build default BAPI + version routing dict
    default_bapi = bapi.get("function", "BAPI_UNDEFINED")
    version_bapi_map = {}
    for ver_code, ver_cfg in sorted(version_rt.items()):
        if "use_bapi" in ver_cfg:
            version_bapi_map[ver_code] = ver_cfg["use_bapi"]

    # DQ rule imports — only include rules actually referenced
    dq_rule_imports = sorted({g["rule"] for g in dq_gates_sorted})

    # Sample rows for tests — synthesize from the source field list
    sample_row = _synthesize_sample_row(definition, value_maps_sorted)
    live_sample_row = _synthesize_sample_row(definition, value_maps_sorted)

    ctx = {
        "object_type":           obj,
        "class_name":            f"{obj}SpineOrchestrator",
        "snake_name":            snake,
        "source_key_field":      definition["source_key_field"],
        "home_table":            definition["home_table"],
        "category":              definition.get("category", "Master"),
        "phase":                 definition.get("phase", "explore"),
        "source_sha":            source_sha,
        "scaffolder_version":    SCAFFOLDER_VERSION,

        "field_maps_sorted":     field_maps_sorted,
        "item_field_maps_sorted": item_field_maps_sorted,
        "value_maps_sorted":     value_maps_sorted,
        "constants_header_sorted": sorted(constants_header.items()),
        "constants_item_sorted":   sorted(constants_item.items()),
        "dq_gates_sorted":       dq_gates_sorted,
        "dq_rule_imports":       dq_rule_imports,
        "fk_fields_sorted":      fk_fields_sorted,

        "extension_structure":   bapi.get("extension_structure", ""),
        "bapi_header_struct":    bapi.get("header_struct", "HEADER"),
        "bapi_header_is_scalar": bapi.get("header_is_scalar", False),
        "bapi_headerx_struct":   bapi.get("headerx_struct", ""),
        "bapi_item_struct":      bapi.get("item_struct", ""),
        "bapi_itemx_struct":     bapi.get("itemx_struct", ""),
        "bapi_return_key":       bapi.get("return_key_field", "NUMBER"),
        "bapi_commit_with_wait": bapi.get("commit_with_wait", True),
        "default_bapi":          default_bapi,
        "version_bapi_map_sorted": sorted(version_bapi_map.items()),

        "verify_key_field":      verify.get("key_field", definition["source_key_field"]),
        "verify_value_fields":   list(verify.get("value_fields", [])),

        "load_primary_lane":     load.get("primary_lane", "BAPI"),
        "load_fallback_lane":    load.get("fallback_lane", ""),

        # Lane: MC
        "mc_object_id":          (load.get("mc", {}) or {}).get("object_id", obj.upper()),
        "mc_staging_template":   (load.get("mc", {}) or {}).get("staging_template", f"S_{obj.upper()}"),
        "primary_table_name":    primary_table.get("name", ""),
        "non_primary_tables":    non_primary_tables,
        "extract_package_size":         extract.get("package_size", 1000),
        "extract_max_rows_per_template": extract.get("max_rows_per_template", 50000),

        # Lane: IDoc
        "idoc_basic_type":       (load.get("idoc", {}) or {}).get("basic_type", f"{obj.upper()}01"),
        "idoc_message_type":     (load.get("idoc", {}) or {}).get("message_type", obj.upper()),
        "idoc_header_segment":   f"E1{obj[:5].upper()}",
        "idoc_receiver_logsys":  "S4HCLNT100",

        # Lane: LTMOM
        "ltmom_source_object":   (load.get("ltmom", {}) or {}).get("source_object", f"S_{obj.upper()}_HEADER"),
        "ltmom_target_object":   (load.get("ltmom", {}) or {}).get("target_object", definition["source_key_field"]),

        # Telemetry passthroughs (used by Step Functions wrappers)
        "telemetry_category":    telemetry.get("category", ""),
        "telemetry_affects":     telemetry.get("affects", []),

        # Test fixtures
        "sample_row":            sample_row,
        "live_sample_row":       live_sample_row,
    }
    return ctx


def _synthesize_sample_row(definition: dict, value_maps_sorted: list) -> dict:
    """Build a sample row that satisfies the DQ gates so unit tests have a
    valid baseline to mutate. Each DQ gate gets a representative value."""
    src_key = definition["source_key_field"]
    row: dict = {src_key: f"{src_key}_T0001"}

    # Heuristic values per rule kind — keep deterministic.
    rule_default_value = {
        "non_empty":              "value",
        "positive_number":        "1",
        "non_negative_number":    "0",
        "iso_date":               "20260614",
        "sap_unit_of_measure":    "EA",
        "currency_iso_4217":      "USD",
        "material_number_format": "MAT_T0001",
        "bukrs_company_code":     "1010",
        "werks_plant":            "1710",
        "langu_code":             "EN",
        "sap_client_3char":       "100",
        "decimal_max_digits":     "100.00",
        "regex_match":            "value",
        "in_set":                 "value",
        "fk_required_when":       "value",
    }

    dq_gates = (definition.get("transform", {}) or {}).get("dq_gates", []) or []
    for g in dq_gates:
        field = g["field"]
        if field in row:
            continue
        val = rule_default_value.get(g["rule"], "value")
        # in_set needs a value from the allowed set
        if g["rule"] == "in_set":
            vals = g.get("rule_args", {}).get("values") or []
            if vals:
                val = vals[0]
        row[field] = val

    # Make sure every field in field_maps + item_field_maps has a non-empty
    # value (so build_payload produces something usable during BAPI dispatch
    # tests + the live smoke).
    tx = definition.get("transform", {}) or {}
    for src in tx.get("field_maps", {}).keys():
        row.setdefault(src, "X")
    for src in tx.get("item_field_maps", {}).keys():
        row.setdefault(src, "X")

    return row


def _render(template_name: str, ctx: dict) -> str:
    try:
        from jinja2 import Environment, FileSystemLoader, select_autoescape
    except ImportError:
        raise SystemExit("jinja2 package not installed (pip install jinja2)")

    env = Environment(
        loader=FileSystemLoader(str(TEMPLATES_DIR)),
        autoescape=False,           # we generate Python/JSON, not HTML
        trim_blocks=True,
        lstrip_blocks=True,
        keep_trailing_newline=True,
    )
    env.filters["repr"]     = _python_repr
    env.filters["reprdict"] = _repr_dict
    env.filters["tojson"]   = lambda v: json.dumps(v, sort_keys=True, separators=(",", ":"))

    # Closure for the test template's "lookup_source_field" helper
    field_maps = dict(ctx["field_maps_sorted"])
    inverse = {tgt: src for src, tgt in field_maps.items()}

    def lookup_source_field(tgt):
        return inverse.get(tgt)

    env.globals["lookup_source_field"] = lookup_source_field

    tmpl = env.get_template(template_name)
    return tmpl.render(**ctx)


# ─────────────────────────────────────────────────────────────────────────────
# Code generation main loop
# ─────────────────────────────────────────────────────────────────────────────
def _generate_one(name_or_path: str, *, check_only: bool = False, verbose: bool = True) -> tuple[bool, list[str]]:
    """Generate (or check) artifacts for one object.

    Returns (ok, changed_files). If check_only=True and any file would change,
    ok=False and changed_files lists them.
    """
    path, definition, raw = _load_definition(name_or_path)
    obj = definition["object_type"]
    snake = _snake_case(obj)
    if verbose:
        print(f"== {obj} ==")
        print(f"   def: {path.relative_to(REPO_ROOT)}")

    # Skip manual-generator objects
    if definition.get("generator") == "manual":
        if verbose:
            print("   (skipped: generator=manual)")
        return True, []

    # 1. Schema validation
    schema_errors = _validate_schema(definition)
    if schema_errors:
        if verbose:
            for e in schema_errors:
                print(f"   SCHEMA: {e}")
        return False, []

    # 2. Lint
    from scaffolder.lint import lint_object_definition
    lint_errors = lint_object_definition(definition, str(DEFINITIONS), known_rules())
    if lint_errors:
        if verbose:
            for e in lint_errors:
                print(f"   LINT: {e}")
        return False, []

    # 3. Content SHA from CANONICAL JSON
    canon = _canonical_json(definition)
    source_sha = _sha256(canon)

    # 4. Collision check — refuse to overwrite hand-written files
    spine_dst = LAMBDA_UTILS / f"{snake}_spine.py"
    if spine_dst.exists():
        head = spine_dst.read_text(encoding="utf-8")[:600]
        if "GENERATED FROM definitions/" not in head:
            if verbose:
                print(f"   COLLISION: {spine_dst} exists but is NOT scaffolder-generated.")
                print(f"   Refusing to overwrite. Add 'generator': 'manual' to the JSON to skip,")
                print(f"   or delete the hand-written file once you've ported its logic.")
            return False, []

    ctx = _build_context(definition, source_sha)

    # 5. Render targets
    targets = {
        spine_dst:                                          ("spine.py.j2",                   "py"),
        LAMBDA_UTILS / "tests" / f"test_{snake}_spine.py":  ("test_unit.py.j2",               "py"),
        LAMBDA_UTILS / "tests" / "integration" / f"test_{snake}_live.py":
                                                            ("test_integration.py.j2",        "py"),
        LAMBDA_UTILS / "templates" / snake / f"mc_{snake}.json":
                                                            ("lane_mc.json.j2",               "json"),
        LAMBDA_UTILS / "templates" / snake / f"idoc_{snake}.xml":
                                                            ("lane_idoc.xml.j2",              "xml"),
        LAMBDA_UTILS / "templates" / snake / f"ltmom_source_{snake}.json":
                                                            ("lane_ltmom_source.json.j2",     "json"),
        LAMBDA_UTILS / "templates" / snake / f"ltmom_mapping_{snake}.json":
                                                            ("lane_ltmom_mapping.json.j2",    "json"),
    }

    changed: list[str] = []
    with tempfile.TemporaryDirectory() as tmp:
        tmpdir = Path(tmp)
        for dst, (tname, kind) in targets.items():
            rendered = _render(tname, ctx)
            tmpfile = tmpdir / dst.name
            tmpfile.write_text(rendered, encoding="utf-8")

            # py_compile syntax check on Python output
            if kind == "py":
                try:
                    py_compile.compile(str(tmpfile), doraise=True)
                except py_compile.PyCompileError as e:
                    if verbose:
                        print(f"   PYCOMPILE: {dst.name} failed: {e}")
                    return False, []
            elif kind == "json":
                try:
                    json.loads(rendered)
                except json.JSONDecodeError as e:
                    if verbose:
                        print(f"   JSON: {dst.name} invalid: {e}")
                    return False, []

            # Diff check
            if dst.exists():
                if dst.read_bytes() == tmpfile.read_bytes():
                    continue            # no change
            else:
                pass

            if check_only:
                changed.append(str(dst.relative_to(REPO_ROOT)))
            else:
                dst.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(tmpfile, dst)
                changed.append(str(dst.relative_to(REPO_ROOT)))

    if verbose:
        if check_only:
            if changed:
                print(f"   DRIFT: {len(changed)} file(s) would change")
                for c in changed:
                    print(f"     - {c}")
            else:
                print("   clean (no drift)")
        else:
            if changed:
                print(f"   generated: {len(changed)} file(s)")
                for c in changed:
                    print(f"     + {c}")
            else:
                print("   up-to-date (no changes)")

    return (not changed) if check_only else True, changed


def cmd_one(name: str, check_only: bool) -> int:
    ok, _ = _generate_one(name, check_only=check_only)
    return 0 if ok else 1


def cmd_all(check_only: bool) -> int:
    if not DEFINITIONS.exists():
        print(f"definitions/ directory missing: {DEFINITIONS}")
        return 1
    overall_ok = True
    any_drift = False
    for f in sorted(DEFINITIONS.glob("*.json")):
        if f.name.startswith("_"):
            continue              # _template.json + _overrides/
        ok, changed = _generate_one(str(f), check_only=check_only)
        if not ok:
            overall_ok = False
        if changed:
            any_drift = True
    if check_only:
        return 0 if (overall_ok and not any_drift) else 1
    return 0 if overall_ok else 1


def cmd_sync_rules() -> int:
    n, files = sync_rules()
    if n == 0:
        print("dq_rules: up-to-date (no changes)")
    else:
        print(f"dq_rules: synced {n} file(s) to {DQ_RULES_DEST.relative_to(REPO_ROOT)}")
        for f in files:
            print(f"  + {f}")
    return 0


# ─────────────────────────────────────────────────────────────────────────────
# CLI
# ─────────────────────────────────────────────────────────────────────────────
def main(argv: Optional[list[str]] = None) -> int:
    ap = argparse.ArgumentParser(prog="scaffolder.build",
                                 description="Generate spine modules from JSON definitions.")
    ap.add_argument("object", nargs="?",
                    help="Object name (definitions/<name>.json) or path. "
                         "Omit when using --all or --sync-rules.")
    ap.add_argument("--all", action="store_true",
                    help="Regenerate every object in definitions/ (skips _-prefixed files and generator=manual).")
    ap.add_argument("--check", action="store_true",
                    help="Dry-run: fail non-zero if any generated file would change.")
    ap.add_argument("--sync-rules", action="store_true",
                    help="Sync scaffolder/rules/*.py into lambda/utils/dq_rules/.")
    args = ap.parse_args(argv)

    if args.sync_rules:
        return cmd_sync_rules()

    # Always sync rules before any codegen so the runtime imports succeed.
    if not args.check:
        sync_rules()

    if args.all:
        return cmd_all(check_only=args.check)
    if args.object:
        return cmd_one(args.object, check_only=args.check)

    ap.print_help()
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
